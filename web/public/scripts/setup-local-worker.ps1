# One-shot local Freya diffusion worker setup (Windows / PowerShell).
# From Studio Worker tab (token already substituted):
#   iex "& { $(irm <studio>/scripts/setup-local-worker.ps1) } -Token '<machine-token>'"
#
# Sets FREYA_WORKER_TOKEN from -Token, ensures Docker, starts freya-local-worker on :8091.
# Fresh worker: empty loras/ + checkpoints/ only — no Freya demo Civitai seed installs.
[CmdletBinding()]
param(
  [string]$Token = $env:FREYA_WORKER_TOKEN,
  [string]$ApiUrl = $env:FREYA_API_URL,
  [int]$Port = $(if ($env:FREYA_WORKER_PORT) { [int]$env:FREYA_WORKER_PORT } else { 8091 }),
  [string]$ModelsDir = $(if ($env:FREYA_MODELS_DIR) { $env:FREYA_MODELS_DIR } else { Join-Path $HOME "freya\models" }),
  [string]$Name = $(if ($env:FREYA_WORKER_CONTAINER) { $env:FREYA_WORKER_CONTAINER } else { "freya-local-worker" }),
  [string]$Image = $env:FREYA_WORKER_IMAGE,
  [switch]$NoStart,
  [switch]$NoGpu
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($Token)) {
  Write-Error " -Token (machine token) is required. Generate one in Freya Studio → Worker → Generate machine token."
}

$configDir = Join-Path $env:APPDATA "freya"
$envFile = Join-Path $configDir "local-worker.env"
New-Item -ItemType Directory -Force -Path $configDir | Out-Null
# Empty model trees only — no Civitai / Freya seed assets.
foreach ($sub in @("loras", "checkpoints", ".hf-cache")) {
  New-Item -ItemType Directory -Force -Path (Join-Path $ModelsDir $sub) | Out-Null
}

$envLines = @(
  "# Generated by setup-local-worker.ps1 — do not commit",
  "FREYA_WORKER_TOKEN=$Token",
  "FREYA_WORKER_PORT=$Port",
  "FREYA_MODELS_DIR=$ModelsDir",
  "FREYA_ENGINE_KEEP_LOADED=$($env:FREYA_ENGINE_KEEP_LOADED)",
  "FREYA_WORKER_CONTAINER=$Name"
)
if (-not [string]::IsNullOrWhiteSpace($ApiUrl)) {
  $envLines += "FREYA_API_URL=$ApiUrl"
}
Set-Content -Path $envFile -Value ($envLines -join "`n") -Encoding utf8
Write-Host "Wrote $envFile (FREYA_WORKER_TOKEN set from machine token)"

function Test-Docker {
  try {
    docker info 2>$null | Out-Null
    return $LASTEXITCODE -eq 0
  } catch {
    return $false
  }
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Write-Host "Docker not found. Install Docker Desktop: https://docs.docker.com/desktop/setup/install/windows-install/"
  Write-Error "Docker is required."
}

if (-not (Test-Docker)) {
  Write-Error "Docker is installed but not usable. Start Docker Desktop and re-run."
}

if ([string]::IsNullOrWhiteSpace($Image)) {
  $null = docker image inspect freya-diffusion-worker:local 2>$null
  if ($LASTEXITCODE -eq 0) {
    $Image = "freya-diffusion-worker:local"
  } else {
    $Image = "harbor.dataknife.net/library/freya-diffusion-worker:0.1.0"
  }
}

Write-Host "Using image: $Image"
$null = docker image inspect $Image 2>$null
if ($LASTEXITCODE -ne 0) {
  Write-Host "Pulling $Image ..."
  docker pull $Image
  if ($LASTEXITCODE -ne 0) {
    Write-Error "Could not pull $Image. Build GPU worker from a Freya checkout (Dockerfile.worker) or pass -Image."
  }
}

if ($Image -like "*freya-diffusion-worker:0.1.0*") {
  Write-Host "note: Harbor :0.1.0 is the slim/stub worker. For CUDA Diffusers, build Dockerfile.worker locally."
}

if ($NoStart) {
  Write-Host ""
  Write-Host "Configured. Start when ready with Docker Desktop +:"
  Write-Host "  docker run -d --name $Name -p ${Port}:8091 -e FREYA_WORKER_TOKEN=$Token -e FREYA_MODELS_DIR=/models -v `"${ModelsDir}:/models`" $Image --port 8091 --models-dir /models"
  return
}

$null = docker inspect $Name 2>$null
if ($LASTEXITCODE -eq 0) {
  Write-Host "Removing existing container $Name"
  docker rm -f $Name | Out-Null
}

$dockerArgs = @(
  "run", "-d", "--name", $Name,
  "--restart", "unless-stopped",
  "-p", "${Port}:8091",
  "-e", "FREYA_MODELS_DIR=/models",
  "-e", "FREYA_MODELS_HOST_DIR=$ModelsDir",
  "-e", "FREYA_ENGINE_KEEP_LOADED=0",
  "-e", "FREYA_WORKER_TOKEN=$Token",
  "-v", "${ModelsDir}:/models"
)

if (-not $NoGpu) {
  $dockerArgs += @("--gpus", "all",
    "-e", "NVIDIA_VISIBLE_DEVICES=all",
    "-e", "NVIDIA_DRIVER_CAPABILITIES=compute,utility")
}

$dockerArgs += @($Image, "--port", "8091", "--models-dir", "/models")

Write-Host "Starting $Name on 0.0.0.0:${Port} (models=$ModelsDir)..."
& docker @dockerArgs
if ($LASTEXITCODE -ne 0 -and -not $NoGpu) {
  Write-Host "GPU start failed — retrying without --gpus ..."
  & $PSCommandPath -Token $Token -ApiUrl $ApiUrl -Port $Port -ModelsDir $ModelsDir -Name $Name -Image $Image -NoGpu
  return
}
if ($LASTEXITCODE -ne 0) {
  Write-Error "Failed to start container $Name"
}

Write-Host ""
Write-Host "Worker up: http://127.0.0.1:${Port}/health"
Write-Host "In Freya Studio → Worker:"
Write-Host "  1. Host = this machine's LAN IP (or localhost if API is local), Port = $Port"
Write-Host "  2. Save worker"
if (-not [string]::IsNullOrWhiteSpace($ApiUrl)) {
  Write-Host "  Studio: $ApiUrl"
}
Write-Host "Token file: $envFile"
Write-Host "Logs: docker logs -f $Name"
Write-Host "Stop: docker rm -f $Name"
