#!/usr/bin/env bash
# One-shot local Freya diffusion worker setup (Linux / macOS).
# Invoked from Studio Worker tab:
#   curl -fsSL <studio>/scripts/setup-local-worker.sh | bash -s -- --token <machine-token>
#
# Sets FREYA_WORKER_TOKEN from --token (machine / Studio token), ensures Docker,
# starts (or rebuilds) container freya-local-worker on :8091.
#
# Fresh worker: creates empty loras/ + checkpoints/ dirs only — does NOT download
# or seed any Freya demo / brand Civitai LoRAs or checkpoints. User installs via UI.
set -euo pipefail

TOKEN="${FREYA_WORKER_TOKEN:-}"
API_URL="${FREYA_API_URL:-}"
PORT="${FREYA_WORKER_PORT:-8091}"
MODELS_DIR="${FREYA_MODELS_DIR:-$HOME/freya/models}"
NAME="${FREYA_WORKER_CONTAINER:-freya-local-worker}"
IMAGE="${FREYA_WORKER_IMAGE:-}"
KEEP_LOADED="${FREYA_ENGINE_KEEP_LOADED:-0}"
SKIP_START=0
NO_GPU=0

usage() {
  cat <<'EOF'
Usage: setup-local-worker.sh [options]

  --token TOKEN       Machine / worker bearer (FREYA_WORKER_TOKEN). Required unless already set.
  --api-url URL       Studio origin (informational; written into env file).
  --port PORT         Host port (default 8091).
  --models-dir DIR    Models bind-mount (default ~/freya/models).
  --image IMAGE       Docker image (default: freya-diffusion-worker:local, else Harbor stub).
  --name NAME         Container name (default freya-local-worker).
  --no-start          Configure only; print how to start.
  --no-gpu            Skip --gpus (CPU / stub image).
  -h, --help          Show this help.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --token) TOKEN="${2:-}"; shift 2 ;;
    --api-url|--studio-url) API_URL="${2:-}"; shift 2 ;;
    --port) PORT="${2:-}"; shift 2 ;;
    --models-dir) MODELS_DIR="${2:-}"; shift 2 ;;
    --image) IMAGE="${2:-}"; shift 2 ;;
    --name) NAME="${2:-}"; shift 2 ;;
    --no-start) SKIP_START=1; shift ;;
    --no-gpu) NO_GPU=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ -z "$TOKEN" ]]; then
  echo "error: --token (machine token) is required" >&2
  echo "Generate one in Freya Studio → Worker → Generate machine token" >&2
  exit 1
fi

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/freya"
ENV_FILE="$CONFIG_DIR/local-worker.env"
# Empty model trees only — no Civitai / Freya seed assets.
mkdir -p "$CONFIG_DIR" "$MODELS_DIR/loras" "$MODELS_DIR/checkpoints" "$MODELS_DIR/.hf-cache"

umask 077
cat >"$ENV_FILE" <<EOF
# Generated by setup-local-worker.sh — do not commit
FREYA_WORKER_TOKEN=$TOKEN
FREYA_WORKER_PORT=$PORT
FREYA_MODELS_DIR=$MODELS_DIR
FREYA_ENGINE_KEEP_LOADED=$KEEP_LOADED
FREYA_WORKER_CONTAINER=$NAME
EOF
if [[ -n "$API_URL" ]]; then
  printf 'FREYA_API_URL=%s\n' "$API_URL" >>"$ENV_FILE"
fi
chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE (FREYA_WORKER_TOKEN set from machine token)"

need_cmd() {
  command -v "$1" >/dev/null 2>&1
}

if ! need_cmd docker; then
  echo "Docker not found."
  if need_cmd apt-get && [[ "$(id -u)" -eq 0 ]]; then
    apt-get update -y
    apt-get install -y docker.io
    systemctl enable --now docker || true
  elif need_cmd apt-get; then
    echo "Install Docker, then re-run:"
    echo "  sudo apt-get update && sudo apt-get install -y docker.io"
    echo "  sudo usermod -aG docker \"\$USER\"  # then re-login"
    exit 1
  else
    echo "Install Docker Desktop / Engine, then re-run this script."
    echo "https://docs.docker.com/engine/install/"
    exit 1
  fi
fi

if ! docker info >/dev/null 2>&1; then
  echo "error: docker is installed but not usable (permission or daemon down)." >&2
  echo "Try: sudo usermod -aG docker \"\$USER\" && newgrp docker" >&2
  exit 1
fi

if [[ "$NO_GPU" -eq 0 ]]; then
  if need_cmd nvidia-smi; then
    if ! docker info 2>/dev/null | grep -qi nvidia; then
      echo "note: NVIDIA GPU detected but Docker GPU runtime may be missing."
      echo "      Install nvidia-container-toolkit, then: sudo systemctl restart docker"
    fi
  else
    echo "note: nvidia-smi not found — continuing without GPU checks (--no-gpu to silence)."
  fi
fi

pick_image() {
  if [[ -n "$IMAGE" ]]; then
    echo "$IMAGE"
    return
  fi
  if docker image inspect freya-diffusion-worker:local >/dev/null 2>&1; then
    echo "freya-diffusion-worker:local"
    return
  fi
  # Harbor stub is enough for wiring; GPU Diffusers image is built locally via Dockerfile.worker.
  echo "harbor.dataknife.net/library/freya-diffusion-worker:0.1.0"
}

IMAGE="$(pick_image)"
echo "Using image: $IMAGE"

if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
  echo "Pulling $IMAGE …"
  if ! docker pull "$IMAGE"; then
    echo "error: could not pull $IMAGE" >&2
    echo "Build the GPU worker from a Freya checkout:" >&2
    echo "  git clone <freya-repo> && cd freya && ./scripts/run-local-worker.sh" >&2
    echo "Or set FREYA_WORKER_IMAGE / --image to an image you already have." >&2
    exit 1
  fi
fi

if [[ "$IMAGE" == *"freya-diffusion-worker:0.1.0"* ]] || [[ "$IMAGE" == harbor.dataknife.net/library/freya-diffusion-worker:0.1.0 ]]; then
  echo "note: Harbor :0.1.0 is the slim/stub worker. For CUDA Diffusers, build:"
  echo "  ./scripts/run-local-worker.sh   # from a Freya repo with Dockerfile.worker"
fi

if [[ "$SKIP_START" -eq 1 ]]; then
  echo
  echo "Configured. Start when ready:"
  echo "  FREYA_WORKER_TOKEN='(from $ENV_FILE)' docker run --rm --name $NAME \\"
  echo "    -p ${PORT}:8091 -e FREYA_WORKER_TOKEN -e FREYA_MODELS_DIR=/models \\"
  echo "    -v \"${MODELS_DIR}:/models\" $IMAGE --port 8091 --models-dir /models"
  exit 0
fi

if docker inspect "$NAME" >/dev/null 2>&1; then
  echo "Removing existing container $NAME"
  docker rm -f "$NAME" >/dev/null
fi

ARGS=(
  run -d --name "$NAME"
  --restart unless-stopped
  -p "${PORT}:8091"
  -e FREYA_MODELS_DIR=/models
  -e FREYA_MODELS_HOST_DIR="$MODELS_DIR"
  -e FREYA_ENGINE_KEEP_LOADED="$KEEP_LOADED"
  -e "FREYA_WORKER_TOKEN=$TOKEN"
  -v "${MODELS_DIR}:/models"
)

if [[ "$NO_GPU" -eq 0 ]]; then
  ARGS+=(--gpus all
    -e NVIDIA_VISIBLE_DEVICES="${NVIDIA_VISIBLE_DEVICES:-all}"
    -e NVIDIA_DRIVER_CAPABILITIES=compute,utility)
fi

ARGS+=("$IMAGE" --port 8091 --models-dir /models)

echo "Starting $NAME on 0.0.0.0:${PORT} (models=$MODELS_DIR)…"
if ! docker "${ARGS[@]}"; then
  if [[ "$NO_GPU" -eq 0 ]]; then
    echo "GPU start failed — retrying without --gpus …" >&2
    NO_GPU=1
    exec "$0" --token "$TOKEN" ${API_URL:+--api-url "$API_URL"} --port "$PORT" \
      --models-dir "$MODELS_DIR" --image "$IMAGE" --name "$NAME" --no-gpu
  fi
  exit 1
fi

echo
echo "Worker up: http://127.0.0.1:${PORT}/health"
echo "In Freya Studio → Worker:"
echo "  1. Host = this machine's LAN IP (or localhost if API is local), Port = ${PORT}"
echo "  2. Save worker"
if [[ -n "$API_URL" ]]; then
  echo "  Studio: $API_URL"
fi
echo "Token file: $ENV_FILE"
echo "Logs: docker logs -f $NAME"
echo "Stop: docker rm -f $NAME"
echo "Update image later: ./scripts/update-local-worker.sh --from-cr freya-gpu  # after patching CR spec.image"
